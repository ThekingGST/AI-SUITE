from __future__ import annotations

import json
from abc import ABC, abstractmethod
from pathlib import Path

from shared.logger import get_logger

LOG = get_logger("friday.templates")


class ProjectTemplate(ABC):
    """Base class for project templates."""
    
    @property
    @abstractmethod
    def template_id(self) -> str:
        ...
        
    @property
    @abstractmethod
    def name(self) -> str:
        ...
        
    @property
    @abstractmethod
    def description(self) -> str:
        ...
        
    @property
    @abstractmethod
    def language(self) -> str:
        ...
        
    @property
    def icon(self) -> str:
        return "code"
        
    @abstractmethod
    def create(self, project_path: Path) -> None:
        """Generate the project structure at the given path."""
        ...


class ProjectTemplateRegistry:
    """Registry for managing project templates."""
    
    def __init__(self) -> None:
        self._templates: dict[str, ProjectTemplate] = {}
        
    def register(self, template: ProjectTemplate) -> None:
        """Register a new project template."""
        if template.template_id in self._templates:
            LOG.warning(f"Template with ID {template.template_id} is already registered. Overwriting.")
        self._templates[template.template_id] = template
        LOG.debug(f"Registered template: {template.template_id}")
        
    def get_templates(self) -> list[ProjectTemplate]:
        """Get all registered templates."""
        return list(self._templates.values())
        
    def get_template(self, template_id: str) -> ProjectTemplate | None:
        """Get a template by its ID."""
        return self._templates.get(template_id)
        
    def get_by_language(self, language: str) -> list[ProjectTemplate]:
        """Get templates that match a specific language."""
        return [t for t in self._templates.values() if t.language.lower() == language.lower()]


class PythonProjectTemplate(ProjectTemplate):
    """Template for a standard Python project."""
    
    @property
    def template_id(self) -> str:
        return "python"
        
    @property
    def name(self) -> str:
        return "Python Project"
        
    @property
    def description(self) -> str:
        return "A standard Python project with src directory, main script, and standard ignores."
        
    @property
    def language(self) -> str:
        return "Python"
        
    def create(self, project_path: Path) -> None:
        project_path.mkdir(parents=True, exist_ok=True)
        project_name = project_path.name
        
        # Create src dir
        src_dir = project_path / "src"
        src_dir.mkdir(exist_ok=True)
        
        # Create src/__init__.py
        (src_dir / "__init__.py").touch()
        
        # Create main.py
        main_py = project_path / "main.py"
        main_py.write_text(
            '"""\n'
            f'Main entry point for {project_name}.\n'
            '"""\n\n'
            'def main() -> None:\n'
            '    """Execute main application logic."""\n'
            '    print("Hello from FRIDAY Python Project!")\n\n'
            'if __name__ == "__main__":\n'
            '    main()\n'
        )
        
        # Create requirements.txt
        req_txt = project_path / "requirements.txt"
        req_txt.write_text("# Add your project dependencies here\n")
        
        # Create .gitignore
        gitignore = project_path / ".gitignore"
        gitignore.write_text(
            "# Python\n"
            "__pycache__/\n"
            "*.py[cod]\n"
            "*$py.class\n\n"
            "# Environments\n"
            ".env\n"
            ".venv\n"
            "env/\n"
            "venv/\n\n"
            "# Distribution / packaging\n"
            "dist/\n"
            "build/\n"
            "*.egg-info/\n\n"
            "# Testing\n"
            ".pytest_cache/\n"
            "coverage.xml\n"
            "htmlcov/\n"
        )
        
        # Create README.md
        readme = project_path / "README.md"
        readme.write_text(f"# {project_name}\n\nA Python project generated by FRIDAY IDE.\n")


