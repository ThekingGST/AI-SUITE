class NodeProjectTemplate(ProjectTemplate):
    """Template for a Node.js project."""
    
    @property
    def template_id(self) -> str:
        return "node"
        
    @property
    def name(self) -> str:
        return "Node.js Project"
        
    @property
    def description(self) -> str:
        return "A basic Node.js project setup with package.json."
        
    @property
    def language(self) -> str:
        return "JavaScript"
        
    def create(self, project_path: Path) -> None:
        project_path.mkdir(parents=True, exist_ok=True)
        project_name = project_path.name
        
        # Create src dir
        src_dir = project_path / "src"
        src_dir.mkdir(exist_ok=True)
        
        # Create src/index.js
        index_js = src_dir / "index.js"
        index_js.write_text(
            '/**\n'
            ' * Main entry point.\n'
            ' */\n'
            'console.log("Hello from FRIDAY Node.js Project!");\n'
        )
        
        # Create package.json
        package_json = project_path / "package.json"
        pkg_data = {
            "name": project_name.lower().replace(" ", "-"),
            "version": "1.0.0",
            "description": "A Node.js project",
            "main": "src/index.js",
            "scripts": {
                "start": "node src/index.js",
                "test": 'echo "Error: no test specified" && exit 1'
            },
            "keywords": [],
            "author": "",
            "license": "ISC"
        }
        package_json.write_text(json.dumps(pkg_data, indent=2) + "\\n")
        
        # Create .gitignore
        gitignore = project_path / ".gitignore"
        gitignore.write_text(
            "# Dependencies\n"
            "node_modules/\n\n"
            "# Build files\n"
            "dist/\n"
            "build/\n\n"
            "# Environment variables\n"
            ".env\n\n"
            "# Logs\n"
            "npm-debug.log*\n"
            "yarn-debug.log*\n"
            "yarn-error.log*\n"
        )
        
        # Create README.md
        readme = project_path / "README.md"
        readme.write_text(f"# {project_name}\n\nA Node.js project generated by FRIDAY IDE.\n")


